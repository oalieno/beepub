// Writes the reader's generated font stylesheets (src/lib/reader/fonts/):
//
// - lxgw-wenkai-tc.css: the Kai, from the fontsource package — the
//   regular weight's slices, WOFF2 only. (The package's own stylesheet
//   names a WOFF fallback beside every WOFF2 slice; the bundler would
//   ship both, 15 MB of files no browser this app runs in asks for.)
// - legacy-ming.css: the Ming's slices again under each of the old font
//   names in legacy-ming.json, so a book that asks for one of them by
//   name is set in the Ming served with the app.
//
// Run after a package is updated or a name is added:
//
//   node scripts/build-reader-fonts.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = "node_modules/@fontsource/lxgw-wenkai-tc";
const out = "src/lib/reader/fonts/lxgw-wenkai-tc.css";
const files = path
  .relative(path.dirname(path.join(root, out)), path.join(root, pkg, "files"))
  .split(path.sep)
  .join("/");

const source = fs.readFileSync(path.join(root, pkg, "400.css"), "utf8");
const faces = source
  .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, "")
  .replace(/url\(\.\/files\//g, `url(${files}/`);
if (/\.woff\)/.test(faces)) throw new Error("a WOFF source is left");
const { version } = JSON.parse(
  fs.readFileSync(path.join(root, pkg, "package.json"), "utf8"),
);
fs.writeFileSync(
  path.join(root, out),
  `/* LXGW WenKai TC (霞鶩文楷), SIL OFL 1.1 — generated by
   scripts/build-reader-fonts.mjs from @fontsource/lxgw-wenkai-tc ${version}.
   Do not edit. */\n${faces}`,
);
console.log(`${out}: ${(faces.match(/@font-face/g) ?? []).length} faces`);

// The legacy Ming names, each given the Ming's own slices.
{
  const pkg = "node_modules/@fontsource-variable/noto-serif-tc";
  const out = "src/lib/reader/fonts/legacy-ming.css";
  const files = path
    .relative(path.dirname(path.join(root, out)), path.join(root, pkg, "files"))
    .split(path.sep)
    .join("/");
  const names = JSON.parse(
    fs.readFileSync(
      path.join(root, "src/lib/reader/fonts/legacy-ming.json"),
      "utf8",
    ),
  );
  const source = fs
    .readFileSync(path.join(root, pkg, "wght.css"), "utf8")
    .replace(/\/\*[^*]*\*\/\n?/g, "")
    .replace(/url\(\.\/files\//g, `url(${files}/`);
  if (!source.includes("font-family: 'Noto Serif TC Variable';"))
    throw new Error("the Ming's family name is not where it was");
  const { version } = JSON.parse(
    fs.readFileSync(path.join(root, pkg, "package.json"), "utf8"),
  );
  const faces = names
    .map((name) =>
      source.replaceAll(
        "font-family: 'Noto Serif TC Variable';",
        `font-family: "${name}";`,
      ),
    )
    .join("\n");
  fs.writeFileSync(
    path.join(root, out),
    `/* Old Ming font names set in Noto Serif TC, SIL OFL 1.1 — generated by
   scripts/build-reader-fonts.mjs from @fontsource-variable/noto-serif-tc ${version}.
   Do not edit. */\n${faces}`,
  );
  console.log(`${out}: ${(faces.match(/@font-face/g) ?? []).length} faces`);
}
